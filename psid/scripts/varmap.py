def labels(path):
    out = {}
    for line in open(path, encoding="latin-1"):
        m = re.match(r'\s*label variable\s+(\S+)\s+"(.*?)"', line)
        if m: out[m[1].upper()] = re.sub(r"\s+", " ", m[2].strip())
    return out


def codebook(paths):
    """var -> list of [lo, hi, text] rows of its value table."""
    cb = {}
    for path in paths:
        cur, buf = None, []
        lines = open(path, encoding="utf-8", errors="replace").read().split("\n") + ['V0 "END"']
        for line in lines:
            if re.match(r"^\s*Page \d+ of \d+", line) or re.match(r"^\s*J3660\d\d\s*$", line): continue
            m = re.match(r'^((?:V|ER)\d+[A-Z_]*)\s+"', line)
            if m:
                if cur and cur not in cb: cb[cur] = buf
                cur, buf = m[1], []
            elif cur: buf.append(line)
    tables = {}
    for v, lines in cb.items():
        i = next((k for k, l in enumerate(lines) if "Value/Range Code" in l), None)
        rows = []
        for l in (lines[i + 1:] if i is not None else []):
            m = re.match(rf"^\s{{6,}}({NUM})(?:\s+-\s+({NUM}))?\s+(\S.*)$", l)
            if m:
                lo = float(m[1].replace(",", "")); hi = float(m[2].replace(",", "")) if m[2] else lo
                rows.append([lo, hi, m[3].strip()])
            elif rows and l.strip() and not re.match(r"^\s*(Non-comparability|F-|I-)", l):
                rows[-1][2] += " " + l.strip()
        tables[v] = rows
    return tables


def codes(rows):
    na, top, bot = [], "", ""
    for lo, hi, text in rows or []:
        if lo == hi and NA_RX.match(text): na.append(lo)
        elif lo == hi and TOP_RX.search(text) and "Actual" not in text:
            if lo > 0: top = lo
            elif lo < 0: bot = lo
    fmt = lambda x: ("%d" % x) if float(x).is_integer() else ("%g" % x)
    return " ".join(fmt(x) for x in na), (fmt(top) if top != "" else ""), (fmt(bot) if bot != "" else "")


