def per_units(rows):
    """Time-unit codes of a *_per variable as 'code=periods_per_year ...' (e.g. '3=52 4=26 5=12 6=1 7=other')."""
    out = []
    for lo, hi, text in rows or []:
        for rx, n in UNITS:
            if lo == hi and re.match(rx, text, re.I): out.append("%d=%s" % (lo, n)); break
    return " ".join(out)


